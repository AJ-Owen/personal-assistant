import os
import time
from datetime import datetime, timedelta, timezone

import pytest

from app.ai import llm
from app.config import settings
from app.processors.daily_summary import generate_daily_summary
from tests.conftest import FakeClient, response, text_block


def _write(p, mtime_epoch=None):
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text("some note content", encoding="utf-8")
    if mtime_epoch is not None:
        os.utime(p, (mtime_epoch, mtime_epoch))


_MODEL_OUTPUT = "<YESTERDAY>\n- shipped the thing\n</YESTERDAY>\n<TODO>\n- ship the next thing\n</TODO>"


@pytest.mark.asyncio
async def test_generates_note_and_excludes_machine_files(tmp_path, monkeypatch):
    monkeypatch.setattr(settings, "vault_path", str(tmp_path))
    monkeypatch.delenv("TZ", raising=False)

    # With TZ unset the processor runs in UTC — compute test dates in UTC too
    yesterday = (datetime.now(timezone.utc) - timedelta(days=1)).date()
    y_epoch = time.time() - 24 * 3600

    _write(tmp_path / f"notes/daily/{yesterday}.md", y_epoch)
    _write(tmp_path / "notes/wiki/topic.md", y_epoch)
    # Machine-generated churn that must NOT be fed to the summary
    _write(tmp_path / f"archive/audit/{yesterday}.md", y_epoch)
    _write(tmp_path / f"archive/inbox/{yesterday}.md", y_epoch)
    _write(tmp_path / settings.inbox_filename, y_epoch)

    client = FakeClient([response("end_turn", text_block(_MODEL_OUTPUT))])
    monkeypatch.setattr(llm, "get_client", lambda: client)

    await generate_daily_summary()

    prompt = client.messages.calls[0]["messages"][0]["content"]
    assert "notes/wiki/topic.md" in prompt
    assert "archive/audit" not in prompt

    today_note = (tmp_path / f"notes/daily/{datetime.now(timezone.utc).date()}.md").read_text()
    assert "## Yesterday" in today_note
    assert "shipped the thing" in today_note
    assert "ship the next thing" in today_note


@pytest.mark.asyncio
async def test_skips_when_already_generated(tmp_path, monkeypatch):
    monkeypatch.setattr(settings, "vault_path", str(tmp_path))
    monkeypatch.delenv("TZ", raising=False)

    yesterday = (datetime.now(timezone.utc) - timedelta(days=1)).date()
    _write(tmp_path / f"notes/daily/{yesterday}.md", time.time() - 24 * 3600)

    today = datetime.now(timezone.utc).date()
    existing = f"---\ntype: daily\ndate: {today}\n---\n\n## Yesterday\n\n- already here\n"
    p = tmp_path / f"notes/daily/{today}.md"
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(existing, encoding="utf-8")

    client = FakeClient([response("end_turn", text_block(_MODEL_OUTPUT))])
    monkeypatch.setattr(llm, "get_client", lambda: client)

    await generate_daily_summary()

    # Existing generated note is left untouched
    assert p.read_text() == existing


_TEMPLATE_NOTE = """\
---
type: daily
tags: daily
aliases: []
date:
---

`$= await dv.view("meta/js/header")`

## Yesterday

_Generated by daily summary agent_

## Objectives Today

_Max 3-5 key results_

## TODO

_Generated by daily summary agent_

- [ ]

## Notes Created Yesterday
"""


@pytest.mark.asyncio
async def test_fills_template_placeholders_and_empty_date(tmp_path, monkeypatch):
    """Notes pre-created by the Obsidian daily-notes template contain
    '## Yesterday' with placeholder text — they must be populated, not skipped,
    and the empty `date:` frontmatter field must be filled."""
    monkeypatch.setattr(settings, "vault_path", str(tmp_path))
    monkeypatch.delenv("TZ", raising=False)

    yesterday = (datetime.now(timezone.utc) - timedelta(days=1)).date()
    _write(tmp_path / f"notes/daily/{yesterday}.md", time.time() - 24 * 3600)

    today = datetime.now(timezone.utc).date()
    p = tmp_path / f"notes/daily/{today}.md"
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(_TEMPLATE_NOTE, encoding="utf-8")

    client = FakeClient([response("end_turn", text_block(_MODEL_OUTPUT))])
    monkeypatch.setattr(llm, "get_client", lambda: client)

    await generate_daily_summary()

    note = p.read_text()
    assert "_Generated by daily summary agent_" not in note
    assert "shipped the thing" in note
    assert "ship the next thing" in note
    assert f"date: {today}" in note
    # Untouched template sections survive
    assert "_Max 3-5 key results_" in note
    assert "- [ ]" in note


@pytest.mark.asyncio
async def test_fills_only_placeholder_sections(tmp_path, monkeypatch):
    """A hand-written Yesterday section is preserved; only the remaining
    placeholder (TODO) is replaced."""
    monkeypatch.setattr(settings, "vault_path", str(tmp_path))
    monkeypatch.delenv("TZ", raising=False)

    yesterday = (datetime.now(timezone.utc) - timedelta(days=1)).date()
    _write(tmp_path / f"notes/daily/{yesterday}.md", time.time() - 24 * 3600)

    today = datetime.now(timezone.utc).date()
    note = _TEMPLATE_NOTE.replace(
        "## Yesterday\n\n_Generated by daily summary agent_",
        "## Yesterday\n\n- hand-written entry",
    )
    p = tmp_path / f"notes/daily/{today}.md"
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(note, encoding="utf-8")

    client = FakeClient([response("end_turn", text_block(_MODEL_OUTPUT))])
    monkeypatch.setattr(llm, "get_client", lambda: client)

    await generate_daily_summary()

    result = p.read_text()
    assert "- hand-written entry" in result
    assert "shipped the thing" not in result  # human Yesterday kept
    assert "ship the next thing" in result    # TODO placeholder filled
    assert "_Generated by daily summary agent_" not in result
